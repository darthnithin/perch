#!/usr/bin/env python3
"""Prepare a custom-tap formula from verified local release archives.

Does not create a tap, publish downloads, install software or choose a license.
The generated URLs work only after the release is published and accessible.
"""
import argparse
import hashlib
from pathlib import Path
import re

TARGETS = ("darwin-arm64", "darwin-amd64", "linux-arm64", "linux-amd64")


def generate(version, directory, repository="darthnithin/perch"):
    if not re.fullmatch(r"v?\d+\.\d+\.\d+(?:[-.][A-Za-z0-9.-]+)?", version):
        raise ValueError("expected a release version such as v0.1.0-preview.2")
    if not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]*/[A-Za-z0-9_][A-Za-z0-9_.-]*", repository):
        raise ValueError("expected a GitHub owner/repository")
    filenames = {f"perch-{version}-{target}.tar.gz" for target in TARGETS}
    sums = {}
    for line in (directory / f"SHA256SUMS-{version}.txt").read_text().splitlines():
        fields = line.split()
        if len(fields) != 2 or not re.fullmatch(r"[0-9a-f]{64}", fields[0]):
            raise ValueError("invalid checksum record")
        digest, filename = fields
        if filename not in filenames or filename in sums:
            raise ValueError("unexpected or duplicate checksum filename")
        sums[filename] = digest
    if set(sums) != filenames:
        raise ValueError("all four target checksums are required")
    for filename, expected in sums.items():
        actual = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
        if actual != expected:
            raise ValueError(f"archive checksum mismatch: {filename}")

    lines = [
        "# Generated by tools/homebrew_formula.py; do not edit checksums manually.",
        "# Prepared for a custom tap. Draft/private URLs are not public downloads.",
        "# Select the project/artwork license before public distribution.",
        "class Perch < Formula",
        '  desc "Terminal workspace for UCSC Hummingbird"',
        f'  homepage "https://github.com/{repository}"',
        f'  version "{version.removeprefix("v")}"',
        "",
    ]
    for platform, system in (("macos", "darwin"), ("linux", "linux")):
        lines.append(f"  on_{platform} do")
        for arch, machine in (("arm", "arm64"), ("intel", "amd64")):
            filename = f"perch-{version}-{system}-{machine}.tar.gz"
            lines += [f"    on_{arch} do",
                      f'      url "https://github.com/{repository}/releases/download/{version}/{filename}"',
                      f'      sha256 "{sums[filename]}"', "    end"]
        lines += ["  end", ""]
    lines += [
        "  def install",
        '    bin.install "perch"',
        '    doc.install "README.md", "ARCHITECTURE.md", "THIRD_PARTY_NOTICES.md",',
        '                "docs", "examples", "assets", "third_party"',
        "  end", "",
        "  def caveats",
        "    <<~EOS",
        "      Try Perch offline: perch --demo --no-config",
        "      Save your Hummingbird SSH destination: perch setup",
        "      For the reference appearance, install Ioskeley Mono and open:",
        "        #{opt_prefix}/share/doc/perch/docs/terminal/Perch-Ioskeley.terminal",
        "      The profile and font are optional; installation does not change your terminal.",
        "    EOS",
        "  end", "",
        "  test do",
        '    require "json"',
        f'    assert_equal "perch {version}", shell_output("#{{bin}}/perch version").strip',
        '    result = JSON.parse(shell_output("#{bin}/perch jobs --demo --no-config --json"))',
        '    assert_equal "demo", result.fetch("source")',
        '    refute_empty result.fetch("data")',
        "  end", "end", "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version")
    parser.add_argument("--archives", type=Path, default=Path("dist"))
    parser.add_argument("--repository", default="darthnithin/perch")
    parser.add_argument("--output", type=Path, default=Path("output/homebrew/perch.rb"))
    args = parser.parse_args()
    try:
        formula = generate(args.version, args.archives, args.repository)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Cannot prepare formula: {error}\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(formula)
    print(f"Prepared {args.output}; no tap, release or installation was published.")


if __name__ == "__main__":
    main()
